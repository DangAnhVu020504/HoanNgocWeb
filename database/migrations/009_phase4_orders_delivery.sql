-- Hợp đồng, Giao COD, Giao hàng theo xe.
--
-- Các chứng từ này dùng BẢNG RIÊNG (TBAOGIA/TDATHANG/TDATHANGNCC/THOPDONG/
-- TGUIHANGCOD/TKETQUAGUICOD/TGIAOHANGTHEOXE) — KHÔNG qua TDONHANG đa năng,
-- nên không cần W_DOC_TYPE_MAP (quy tắc vàng 5 không áp dụng cho LOAI/MODE).
-- Số phiếu web sinh từ W_DOC_SEQUENCE theo tiền tố desktop (BG/DH/DN/HĐ/COD/KQ/XE).
-- Idempotent.
-- ============================================================

-- Sequence số phiếu web (web-only, không xung đột desktop)
INSERT INTO W_DOC_SEQUENCE (PREFIX_, YEAR_, LAST_SEQ)
SELECT p.PREFIX, YEAR(CURDATE()), 0
FROM (
  SELECT 'BG'  AS PREFIX UNION ALL  -- Báo giá
  SELECT 'DH'  UNION ALL            -- Đặt hàng KH
  SELECT 'DN'  UNION ALL            -- Đặt mua NCC (đặt hàng nhà cung cấp)
  SELECT 'HD'  UNION ALL            -- Hợp đồng
  SELECT 'COD' UNION ALL            -- Gửi hàng COD
  SELECT 'KQ'  UNION ALL            -- Kết quả gửi COD
  SELECT 'XE'                       -- Giao hàng theo xe
) p
WHERE NOT EXISTS (
  SELECT 1 FROM W_DOC_SEQUENCE s WHERE s.PREFIX_ = p.PREFIX AND s.YEAR_ = YEAR(CURDATE())
);

