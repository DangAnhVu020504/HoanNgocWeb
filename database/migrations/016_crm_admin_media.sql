-- ---------- CSKH: lịch sử chăm sóc khách hàng ----------
CREATE TABLE IF NOT EXISTS W_CUSTOMER_CARE (
  ID                CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL PRIMARY KEY,
  CUSTOMER_ID       CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  CARE_TYPE         VARCHAR(16) NOT NULL DEFAULT 'CALL',   -- CALL | EMAIL | SMS | ZALO | VISIT | OTHER
  CONTENT           TEXT NULL,
  RESULT            VARCHAR(500) NULL,
  NEXT_CARE_AT      DATETIME(3) NULL,
  ASSIGNEE_USER_ID  CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  CREATED_BY        CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  CREATED_AT        DATETIME(3) NOT NULL,
  UPDATED_AT        DATETIME(3) NULL,
  KEY IX_WCARE_CUSTOMER (CUSTOMER_ID, CREATED_AT),
  KEY IX_WCARE_NEXT (NEXT_CARE_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ---------- CSKH: phản hồi / đánh giá khách hàng ----------
CREATE TABLE IF NOT EXISTS W_CUSTOMER_FEEDBACK (
  ID           CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL PRIMARY KEY,
  CUSTOMER_ID  CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  INVOICE_ID   CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  RATING       TINYINT NOT NULL DEFAULT 5,
  CONTENT      VARCHAR(2000) NULL,
  STATUS       VARCHAR(16) NOT NULL DEFAULT 'NEW',        -- NEW | PROCESSING | RESOLVED
  RESPONSE     VARCHAR(2000) NULL,
  CREATED_BY   CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  CREATED_AT   DATETIME(3) NOT NULL,
  RESPONDED_BY CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  RESPONDED_AT DATETIME(3) NULL,
  KEY IX_WFEEDBACK_CUSTOMER (CUSTOMER_ID, CREATED_AT),
  KEY IX_WFEEDBACK_STATUS (STATUS, CREATED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ---------- CSKH: tin nhắn Email / SMS / Zalo ----------
CREATE TABLE IF NOT EXISTS W_MESSAGE (
  ID             CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL PRIMARY KEY,
  CHANNEL        VARCHAR(16) NOT NULL,                    -- EMAIL | SMS | ZALO
  CUSTOMER_ID    CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  RECIPIENT      VARCHAR(320) NOT NULL,
  SUBJECT        VARCHAR(500) NULL,
  BODY           TEXT NULL,
  STATUS         VARCHAR(16) NOT NULL DEFAULT 'PENDING',  -- PENDING | SENT | FAILED | NOT_CONFIGURED
  ERROR          TEXT NULL,
  REFERENCE_TYPE VARCHAR(64) NULL,
  REFERENCE_ID   CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  CREATED_BY     CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  CREATED_AT     DATETIME(3) NOT NULL,
  SENT_AT        DATETIME(3) NULL,
  KEY IX_WMESSAGE_CUSTOMER (CUSTOMER_ID, CREATED_AT),
  KEY IX_WMESSAGE_STATUS (STATUS, CREATED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ---------- Điểm thân thiết: sổ cái điểm ----------
CREATE TABLE IF NOT EXISTS W_LOYALTY_TXN (
  ID             CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL PRIMARY KEY,
  CUSTOMER_ID    CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  TXN_TYPE       VARCHAR(16) NOT NULL,                    -- EARN | REDEEM | ADJUST
  POINTS         INT NOT NULL,                            -- dương = cộng, âm = trừ
  REFERENCE_TYPE VARCHAR(64) NULL,
  REFERENCE_ID   CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  NOTE           VARCHAR(500) NULL,
  CREATED_BY     CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  CREATED_AT     DATETIME(3) NOT NULL,
  KEY IX_WLOYALTY_CUSTOMER (CUSTOMER_ID, CREATED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

