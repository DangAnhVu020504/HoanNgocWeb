-- Sequence số phiếu theo prefix + năm (BS26/00001…) — web-only
INSERT INTO W_DOC_SEQUENCE (PREFIX_, YEAR_, LAST_SEQ)
SELECT p.PREFIX, YEAR(CURDATE()), 0 FROM W_DOC_TYPE_MAP p
WHERE p.DOC_TYPE IN ('BAN_SI','TRA_LAI_KH','XUAT_KHO','CHUYEN_KHO','XUAT_TRA_NCC')
  AND NOT EXISTS (
    SELECT 1 FROM W_DOC_SEQUENCE s
    WHERE s.PREFIX_ = p.PREFIX AND s.YEAR_ = YEAR(CURDATE())
  );

